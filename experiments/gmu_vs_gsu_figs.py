"""Experiment 3: does the mixture structure matter? SVM-GMU vs SVM-GSU.

SVM-GSU is fit on the moment-matched single-Gaussian summary of each GMM. Only
the SGD is stochastic, so we report mean +/- std of the three boundary metrics
over several seeds. Run:

    uv run python experiments/gmu_vs_gsu_figs.py
    uv run python experiments/gmu_vs_gsu_figs.py --smoke
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _common as C  # noqa: E402

X, y, SAMPLE_UNCERTAINTY = C.X, C.y, C.SAMPLE_UNCERTAINTY
MASTER_SEED = C.MASTER_SEED

R_SEEDS_FULL = 30
R_SEEDS_SMOKE = 4


def gmu_gsu_stats(seeds):
    """Fit GMU and GSU per seed; return mean/std of the three GMU-vs-GSU metrics
    plus the GMU-only boundary seed-stability (covers the Exp 1 showcase claim).

    `make_seeds` comes from `_common` (`C.make_seeds`); do not redefine it.
    """
    su_gsu = [C.moment_match_gmm(g) for g in SAMPLE_UNCERTAINTY]
    rows = []
    gmu_boundaries = []
    for s in seeds:
        w_gmu, b_gmu = C.fit_gmu(X, y, SAMPLE_UNCERTAINTY, seed=s)
        w_gsu, b_gsu = C.fit_gmu(X, y, su_gsu, seed=s)
        gmu_boundaries.append((w_gmu, b_gmu))
        rows.append(C.boundary_metrics_2d(w_gsu, b_gsu, w_gmu, b_gmu))
        print(f"seed {s}: angle={rows[-1][0]:.3f} offset={rows[-1][1]:.4f} rms={rows[-1][2]:.4f}")
    arr = np.array(rows)  # (S, 3): angle, offset, rms

    # Exp 1 seed-stability: angle of each seed's GMU boundary to the median GMU
    # boundary. A small std means the showcase boundary is not a lucky draw.
    w_med = np.median(np.array([w for w, _ in gmu_boundaries]), axis=0)
    b_med = float(np.median([b for _, b in gmu_boundaries]))
    gmu_drift = np.array([
        C.boundary_metrics_2d(w, b, w_med, b_med)[0] for w, b in gmu_boundaries
    ])

    return {
        "angle": (float(arr[:, 0].mean()), float(arr[:, 0].std())),
        "offset": (float(arr[:, 1].mean()), float(arr[:, 1].std())),
        "rms": (float(arr[:, 2].mean()), float(arr[:, 2].std())),
        "gmu_stability": (float(gmu_drift.mean()), float(gmu_drift.std()), float(gmu_drift.max())),
        "su_gsu": su_gsu,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--smoke", action="store_true")
    args = parser.parse_args()

    seeds = C.make_seeds(MASTER_SEED, R_SEEDS_SMOKE if args.smoke else R_SEEDS_FULL)
    stats = gmu_gsu_stats(seeds)
    gm, gs, gmax = stats["gmu_stability"]
    print(
        f"angle  = {stats['angle'][0]:.4f} +/- {stats['angle'][1]:.4f} deg\n"
        f"offset = {stats['offset'][0]:.4f} +/- {stats['offset'][1]:.4f}\n"
        f"rms    = {stats['rms'][0]:.4f} +/- {stats['rms'][1]:.4f}\n"
        f"GMU boundary seed-drift (Exp 1) = {gm:.4f} +/- {gs:.4f} deg (max {gmax:.4f})"
    )
    if args.smoke:
        assert stats["angle"][0] < 10.0, "smoke: GMU/GSU angle unexpectedly large"
        assert gmax < 5.0, "smoke: GMU boundary unstable across seeds"
        print("smoke check passed")
        return
    # The three-panel contour comparison figure (gmu_vs_gsu_approximation.pgf)
    # is regenerated by the paired notebook, which owns the contour drawing.
    # This script's role is the seed-aggregated metric block printed above.
    print("metric block above is the publication number for Exp 3")


if __name__ == "__main__":
    main()
